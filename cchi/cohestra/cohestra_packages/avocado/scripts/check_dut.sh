#!/usr/bin/env bash
#*****************************************************************************
# check_dut.sh — contract-check a user DUT against the Avocado DUT interface
# (integration/avocado_dut_if.svh) WITHOUT building the mesh.
#
# Usage:
#   [AVOCADO_DUT_MODULE=<name>] check_dut.sh <user-dut-rtl-file ...>
#
# The user RTL must provide `module avocado_dut` with the contract port list
# (see integration/avocado_dut_template.sv); set AVOCADO_DUT_MODULE when the
# module has a different name. This script generates a tiny harness that
# instantiates the DUT with the contract connection macros and runs verilator
# --lint-only over the composition: any missing, misnamed or mis-sized port
# fails the lint.
#
# Quick self-check against the reference shell:
#   check_dut.sh ../integration/avocado_dut_template.sv
#*****************************************************************************
set -euo pipefail

PKG_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT_DIR="$PKG_DIR/build"
mkdir -p "$OUT_DIR"

if [ "$#" -lt 1 ]; then
    echo "usage: [AVOCADO_DUT_MODULE=<name>] $0 <user-dut-rtl-file ...>" >&2
    exit 2
fi

DUT_MODULE="${AVOCADO_DUT_MODULE:-avocado_dut}"
HARNESS="$OUT_DIR/avocado_dut_check.sv"

cat > "$HARNESS" <<'EOF'
// Generated by check_dut.sh — contract check harness for `AVOCADO_DUT_MODULE.
`include "avocado_dut_if.svh"

module avocado_dut_check (
    input  logic clock,
    input  logic reset,

    `AVOCADO_CCHI_T1_PORT_DECL(0),
    `AVOCADO_CCHI_T1_PORT_DECL(1),
    `AVOCADO_CCHI_T1_PORT_DECL(2),
    `AVOCADO_CCHI_T1_PORT_DECL(3),

    `AVOCADO_CHI_RN_PORT_DECL(0),
    `AVOCADO_CHI_RN_PORT_DECL(1),
    `AVOCADO_CHI_RN_PORT_DECL(2),
    `AVOCADO_CHI_RN_PORT_DECL(3)
);

    `AVOCADO_DUT_MODULE u_dut (
        .clock  (clock),
        .reset  (reset),

        `AVOCADO_CCHI_T1_PORT_CONN(0),
        `AVOCADO_CCHI_T1_PORT_CONN(1),
        `AVOCADO_CCHI_T1_PORT_CONN(2),
        `AVOCADO_CCHI_T1_PORT_CONN(3),

        `AVOCADO_CHI_RN_PORT_CONN(0),
        `AVOCADO_CHI_RN_PORT_CONN(1),
        `AVOCADO_CHI_RN_PORT_CONN(2),
        `AVOCADO_CHI_RN_PORT_CONN(3)
    );

endmodule
EOF

# PINMISSING is waived: optional passive taps (e.g. the mon_chi_rn* CHI
# monitor pins, emitted when the DUT is generated with --chi-mon) may be
# present on the DUT yet unconnected in this harness; a genuinely missing
# contract pin still fails via PINNOTFOUND. WIDTHEXPAND is waived: the
# reference wrapper's intentional 7->8-bit zero-extension adapters fire it.
verilator --lint-only \
    --top-module avocado_dut_check \
    +incdir+"$PKG_DIR/integration" \
    +define+AVOCADO_DUT_MODULE="$DUT_MODULE" \
    -Wno-UNUSEDSIGNAL -Wno-UNUSEDPARAM -Wno-PINCONNECTEMPTY \
    -Wno-DECLFILENAME -Wno-VARHIDDEN -Wno-WIDTHTRUNC \
    -Wno-WIDTHEXPAND \
    -Wno-PINMISSING \
    "$HARNESS" "$@"

echo "check_dut: contract OK (module $DUT_MODULE; $*)"
